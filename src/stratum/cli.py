# --------------------------------------------------------------------------- #
# Small helpers
# --------------------------------------------------------------------------- #


def _version_string() -> str:
    """Return ``stratum <version>`` from :data:`stratum.__version__`."""
    from . import __version__

    return f"stratum {__version__}"


def _resolve_dir(raw: str | None) -> Path:
    """Expand ``--dir`` (or fall back to ``~/.stratum``) to an absolute path."""
    if raw is None:
        return Path.home() / INSTALL_DIR_NAME
    return Path(raw).expanduser().absolute()


def _chmod_private(path: Path, mode: int) -> None:
    """Best-effort ``chmod``; Windows ACLs may not honour POSIX bits."""
    try:
        path.chmod(mode)
    except OSError:  # pragma: no cover - platform dependent
        pass


def _write_text(path: Path, content: str, *, force: bool) -> bool:
    """Write ``content`` to ``path`` unless it exists (or ``force`` is set).

    Returns:
        ``True`` when the file was (re)written, ``False`` when an existing file
        was left untouched.
    """
    if path.exists() and not force:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def _write_secret(path: Path, *, force: bool) -> bool:
    """Create an empty secret placeholder and tighten its permissions."""
    if path.exists() and not force:
        _chmod_private(path, 0o600)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("", encoding="utf-8", newline="\n")
    _chmod_private(path, 0o600)
    return True


def _require_install_dir(target: Path) -> int | None:
    """Return an exit code when ``target`` is not an install directory, else ``None``."""
    if target.is_dir():
        return None
    print(
        f"stratum: no Stratum install found at {target}\n"
        f"  Run 'stratum install --dir {target}' first, or pass --dir <path>.",
        file=sys.stderr,
    )
    return EXIT_ERROR


def _compose(target: Path, compose_args: Sequence[str]) -> int:
    """Run ``docker compose <compose_args>`` inside ``target`` and return its code.

    The command is an explicit argument list with ``check=False`` (never
    ``shell=True``): Docker's own diagnostics reach the user's terminal
    unchanged, and a non-zero exit code is propagated instead of raised.
    """
    if shutil.which("docker") is None:
        print(_DOCKER_MISSING, file=sys.stderr)
        return EXIT_NO_DOCKER
    command = ["docker", "compose", *compose_args]
    try:
        completed = subprocess.run(command, cwd=str(target), check=False)
    except OSError as exc:
        print(f"stratum: could not run {' '.join(command)}: {exc}", file=sys.stderr)
        return EXIT_ERROR
    return int(completed.returncode)


def _health_url() -> str:
    """The readiness endpoint ``status`` probes."""
    return f"http://{DEFAULT_BIND_HOST}:{DEFAULT_HTTP_PORT}/health"


def _print_health() -> None:
    """Fetch and pretty-print the readiness probe; never raises."""
    url = _health_url()
    try:
        with urlopen(url, timeout=HEALTH_TIMEOUT) as response:  # noqa: S310 - fixed http URL
            payload = json.loads(response.read().decode("utf-8"))
    except Exception as exc:  # noqa: BLE001 - a status report must never crash
        print(f"  {url} unreachable ({type(exc).__name__}: {exc})")
        return
    print(json.dumps(payload, indent=2, default=str))


