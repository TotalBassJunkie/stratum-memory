def main(argv: Sequence[str] | None = None) -> int:
    """Dispatch the ``stratum`` CLI.

    Args:
        argv: Argument list (excluding the program name); defaults to
            :data:`sys.argv` via :mod:`argparse`.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(
        prog="stratum", description="Stratum-Memory command-line interface."
    )
    parser.add_argument(
        "--version",
        action="version",
        version=_version_string(),
        help="print the version and exit",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    mcp_parser = subparsers.add_parser("mcp", help="run the MCP server")
    mcp_parser.add_argument("--transport", choices=("stdio", "streamable-http"), default=None)
    mcp_parser.set_defaults(func=_cmd_mcp)

    health_parser = subparsers.add_parser("health", help="print the readiness probe")
    health_parser.set_defaults(func=_cmd_health)

    version_parser = subparsers.add_parser("version", help="print the version")
    version_parser.set_defaults(func=_cmd_version)

    install_parser = subparsers.add_parser(
        "install", help="write the local stack files (compose, .env, secrets)"
    )
    install_parser.add_argument(
        "--dir", default=None, help="install directory (default: ~/.stratum)"
    )
    install_parser.add_argument(
        "--image", default=DEFAULT_IMAGE, help=f"container image (default: {DEFAULT_IMAGE})"
    )
    install_parser.add_argument("--force", action="store_true", help="overwrite existing files")
    install_parser.set_defaults(func=_cmd_install)

    up_parser = subparsers.add_parser("up", help="start the stack (docker compose up -d)")
    up_parser.add_argument("--dir", default=None, help="install directory")
    up_parser.set_defaults(func=_cmd_up)

    down_parser = subparsers.add_parser("down", help="stop the stack (docker compose down)")
    down_parser.add_argument("--dir", default=None, help="install directory")
    down_parser.set_defaults(func=_cmd_down)

    status_parser = subparsers.add_parser("status", help="show containers plus the readiness probe")
    status_parser.add_argument("--dir", default=None, help="install directory")
    status_parser.set_defaults(func=_cmd_status)

    logs_parser = subparsers.add_parser("logs", help="tail the stack's logs")
    logs_parser.add_argument("service", nargs="?", default=None, help="single service name")
    logs_parser.add_argument("--dir", default=None, help="install directory")
    logs_parser.add_argument(
        "-n",
        "--tail",
        type=int,
        default=DEFAULT_LOG_TAIL,
        help=f"number of lines to show (default: {DEFAULT_LOG_TAIL})",
    )
    logs_parser.set_defaults(func=_cmd_logs)

    doctor_parser = subparsers.add_parser("doctor", help="environment diagnostics")
    doctor_parser.add_argument("--dir", default=None, help="install directory to check")
    doctor_parser.set_defaults(func=_cmd_doctor)

    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.command == "mcp":
        forwarded: list[str] = []
        if args.transport is not None:
            forwarded += ["--transport", args.transport]
        return _cmd_mcp(forwarded)
    if args.command == "health":
        return _cmd_health([])
    return args.func(args)


if __name__ == "__main__":  # pragma: no cover - exercised via the console script
    raise SystemExit(main())
