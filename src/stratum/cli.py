@dataclass(frozen=True)
class _Check:
    """One row of the ``doctor`` table."""

    name: str
    ok: bool
    detail: str
    hint: str = ""


def _check_python() -> _Check:
    """Verify the interpreter satisfies :data:`MIN_PYTHON`."""
    minimum = f"{MIN_PYTHON[0]}.{MIN_PYTHON[1]}"
    ok = sys.version_info[:2] >= MIN_PYTHON
    detail = f"{platform.python_version()} ({sys.executable})"
    return _Check(f"Python >= {minimum}", ok, detail, "" if ok else f"install Python {minimum}+")


def _check_docker() -> _Check:
    """Verify a ``docker`` binary is on ``PATH`` and reports a version."""
    if shutil.which("docker") is None:
        return _Check(
            "docker in PATH", False, "not found", "install Docker with the Compose plugin"
        )
    try:
        probe = subprocess.run(
            ["docker", "--version"],
            capture_output=True,
            text=True,
            check=False,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return _Check("docker in PATH", False, f"probe failed: {exc}")
    if probe.returncode != 0:
        return _Check("docker in PATH", False, f"'docker --version' exited {probe.returncode}")
    return _Check("docker in PATH", True, (probe.stdout or probe.stderr).strip())


def _check_port(host: str = DEFAULT_BIND_HOST, port: int = DEFAULT_HTTP_PORT) -> _Check:
    """Verify the HTTP/MCP port can still be bound on ``host``."""
    name = f"port {port} free"
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.bind((host, port))
    except OSError as exc:
        return _Check(
            name,
            False,
            f"{host}:{port} is in use ({exc})",
            "stop the process using it, or point the stack at another port",
        )
    return _Check(name, True, f"{host}:{port} is available")


def _check_install_dir(target: Path) -> _Check:
    """Verify the install directory exists and report how complete it is."""
    if not target.is_dir():
        return _Check(
            "install directory",
            False,
            f"{target} does not exist",
            "run 'stratum install' to create the stack files",
        )
    present = sum(1 for name in (COMPOSE_FILENAME, ENV_FILENAME) if (target / name).is_file())
    return _Check("install directory", True, f"{target} ({present}/2 stack files)")


def _render_checks(checks: Sequence[_Check]) -> None:
    """Print the ``doctor`` checks as an aligned table plus a summary line."""
    name_width = max(len(check.name) for check in checks)
    print("Stratum-Memory doctor\n")
    print(f"{'CHECK':<{name_width}}  {'STATUS':<6}  DETAIL")
    print(f"{'-' * name_width}  {'-' * 6}  {'-' * 40}")
    for check in checks:
        status = "ok" if check.ok else "FAIL"
        print(f"{check.name:<{name_width}}  {status:<6}  {check.detail}")
        if not check.ok and check.hint:
            print(f"{'':<{name_width}}  {'':<6}  -> {check.hint}")
    failed = sum(1 for check in checks if not check.ok)
    print(f"\n{len(checks) - failed}/{len(checks)} checks passed")
    if failed:
        print("Fix the FAIL rows above, then re-run 'stratum doctor'.")


def _cmd_doctor(args: argparse.Namespace) -> int:
    """Run the environment checks; exit 1 when any of them fails."""
    checks = [
        _check_python(),
        _check_docker(),
        _check_port(),
        _check_install_dir(_resolve_dir(args.dir)),
    ]
    _render_checks(checks)
    return EXIT_OK if all(check.ok for check in checks) else EXIT_ERROR


