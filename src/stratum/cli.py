"""Command-line entry point for Stratum-Memory (``stratum`` console script).

Declared in ``pyproject.toml`` as ``stratum = "stratum.cli:main"``. It provides a
minimal, dependency-light dispatcher over the operator commands documented in
``docs/distribution.md``:

* ``stratum mcp``      — start the MCP server (stdio / streamable-http),
  delegating to :func:`stratum.mcp.server.main`, so the ``mcp`` library is
  imported only when the server is actually started.
* ``stratum health``   — print the readiness probe (:func:`stratum.observability.health`)
  as JSON and exit non-zero when the status is not ``ok``.
* ``stratum version``  — print ``stratum <version>`` (from ``stratum.__version__``).
* ``stratum install``  — write a self-contained stack (``docker-compose.yml``,
  ``.env`` and the empty ``secrets/`` placeholders) into the install directory
  (default ``~/.stratum``), so the published container image can be started
  without a checkout of this repository.
* ``stratum up`` / ``stratum down`` — start / stop that stack.
* ``stratum status``   — ``docker compose ps`` plus the ``/health`` probe.
* ``stratum logs``     — tail the stack's logs.
* ``stratum doctor``   — environment diagnostics (Python, Docker, port, install
  directory).

Every Docker interaction shells out to ``docker compose`` via
:func:`subprocess.run` with an explicit argument list and ``check=False`` —
never ``shell=True`` — and a missing ``docker`` binary is reported as exit code
:data:`EXIT_NO_DOCKER` (2) instead of a traceback. Nothing outside the standard
library is imported at import time, so ``stratum version`` works in a minimal
environment.
"""

from __future__ import annotations

import argparse
import json
import platform
import shutil
import socket
import subprocess
import sys
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from urllib.request import urlopen

__all__ = ["main"]

# --------------------------------------------------------------------------- #
# Exit codes and defaults
# --------------------------------------------------------------------------- #

#: Everything worked.
EXIT_OK = 0
#: A check or a command failed (see the message on stderr).
EXIT_ERROR = 1
#: ``docker`` is not on ``PATH``; nothing could be executed.
EXIT_NO_DOCKER = 2

#: The published image every channel resolves to (``docs/distribution.md``).
DEFAULT_IMAGE = "ghcr.io/totalbassjunkie/stratum-memory:latest"
#: Name of the install directory inside the user's home directory.
INSTALL_DIR_NAME = ".stratum"
#: Host/port the stack publishes and the readiness probe listens on.
DEFAULT_BIND_HOST = "127.0.0.1"
DEFAULT_HTTP_PORT = 8088
#: Seconds the ``status`` health probe waits before it declares the stack down.
HEALTH_TIMEOUT = 2.0
#: ``docker compose logs`` default line count.
DEFAULT_LOG_TAIL = 200
#: Minimum interpreter :command:`stratum doctor` accepts.
MIN_PYTHON = (3, 12)

#: Secret files the stack mounts; created as empty placeholders by ``install``.
SECRET_FILES: tuple[str, ...] = ("pg_password", "app_password", "llm_key")

#: Files ``install`` writes next to each other in the install directory.
COMPOSE_FILENAME = "docker-compose.yml"
ENV_FILENAME = ".env"

#: Message printed whenever a stack command cannot run because Docker is absent.
_DOCKER_MISSING = (
    "stratum: 'docker' was not found on PATH.\n"
    "  The stack commands need Docker with the Compose v2 plugin:\n"
    "    https://docs.docker.com/engine/install/\n"
    "  Install Docker (Docker Desktop on Windows/macOS) and re-run."
)

