def _cmd_version(_args: argparse.Namespace) -> int:
    """Print ``stratum <version>`` and exit successfully."""
    print(_version_string())
    return EXIT_OK


def _cmd_install(args: argparse.Namespace) -> int:
    """Write the stack files into the install directory (idempotent)."""
    target = _resolve_dir(args.dir)
    image = str(args.image or DEFAULT_IMAGE)
    force = bool(args.force)

    try:
        target.mkdir(parents=True, exist_ok=True)
        secrets_dir = target / "secrets"
        secrets_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print(f"stratum: cannot create {target}: {exc}", file=sys.stderr)
        return EXIT_ERROR

    _chmod_private(secrets_dir, 0o700)

    written: list[Path] = []
    kept: list[Path] = []
    stack_files = (
        (target / COMPOSE_FILENAME, _COMPOSE_TEMPLATE.replace("__IMAGE__", image)),
        (target / ENV_FILENAME, _ENV_TEMPLATE),
    )
    for path, content in stack_files:
        (written if _write_text(path, content, force=force) else kept).append(path)
    for name in SECRET_FILES:
        path = secrets_dir / name
        (written if _write_secret(path, force=force) else kept).append(path)

    print(f"stratum install: stack in {target}")
    for path in written:
        print(f"  wrote  {path.relative_to(target).as_posix()}")
    for path in kept:
        print(f"  kept   {path.relative_to(target).as_posix()} (exists; use --force to overwrite)")
    if not written and not force:
        print("  nothing to do — re-run with --force to regenerate.")

    print(_next_steps(target))
    return EXIT_OK


def _next_steps(target: Path) -> str:
    """The human-facing instructions printed after a successful ``install``."""
    return (
        "\nNext steps:\n"
        "  1. Fill the three secret placeholders (they are created empty):\n"
        f"       {target / 'secrets' / 'pg_password'}    owner role 'stratum'\n"
        f"       {target / 'secrets' / 'app_password'}   app role 'stratum_app' (core + worker)\n"
        f"       {target / 'secrets' / 'llm_key'}        API key of the LLM/embedding endpoint\n"
        f"  2. Optional: set LLM_BASE_URL / LLM_CHAT_MODEL / LLM_EMBED_MODEL in {target / ENV_FILENAME}\n"
        f"  3. Start the stack:   stratum up --dir {target}\n"
        f"  4. Check it:          stratum status --dir {target}\n"
        "  5. Once the database is up, set the app-role password (first start only):\n"
        f"       cd {target} && docker compose exec stratum-db \\\n"
        "         psql -U stratum -d stratum -c \"ALTER ROLE stratum_app PASSWORD '<secrets/app_password>';\"\n"
    )


def _cmd_up(args: argparse.Namespace) -> int:
    """Start the stack in the background (``docker compose up -d``)."""
    target = _resolve_dir(args.dir)
    code = _require_install_dir(target)
    if code is not None:
        return code
    return _compose(target, ["up", "-d"])


def _cmd_down(args: argparse.Namespace) -> int:
    """Stop and remove the stack's containers (``docker compose down``)."""
    target = _resolve_dir(args.dir)
    code = _require_install_dir(target)
    if code is not None:
        return code
    return _compose(target, ["down"])


def _cmd_status(args: argparse.Namespace) -> int:
    """Show the containers plus, when reachable, the readiness probe."""
    target = _resolve_dir(args.dir)
    code = _require_install_dir(target)
    if code is not None:
        return code

    print(f"Containers ({target}):", flush=True)
    compose_code = _compose(target, ["ps"])
    print("Health probe:", flush=True)
    _print_health()
    return compose_code


def _cmd_logs(args: argparse.Namespace) -> int:
    """Tail the stack's logs (optionally one service)."""
    target = _resolve_dir(args.dir)
    code = _require_install_dir(target)
    if code is not None:
        return code

    compose_args = ["logs", "--tail", str(int(args.tail))]
    if args.service:
        compose_args.append(str(args.service))
    return _compose(target, compose_args)


